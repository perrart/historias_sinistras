#!/usr/bin/env python3
"""Generate embedded fonts (.vlw arrays) and pixel art masks for HISTÓRIAS SINISTRAS.

Output:
  src/AssetFonts.h  - smooth (anti-aliased) VLW fonts with full PT-BR coverage
  src/AssetArt.h    - 8-bit alpha masks (fingerprint, eye) drawn in any colour

Run from the project root:  python3 tools/gen_assets.py
Requires: pip install freetype-py pillow
"""
import math
import os
import random
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from vlwgen import make_vlw, DEFAULT_CHARS  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FONT_DIR = os.path.join(ROOT, 'assets', 'fonts')
SRC = os.path.join(ROOT, 'src')

# Characters every font must cover (spec section 10)
REQUIRED = 'áàâãéêíóôõúçÁÉÍÓÚÇÀÂÃÊÔÕ'

TITLE_XL_CHARS = (list(range(0x20, 0x60)) + list(range(0xC0, 0xDE)) + [0x2014])

FONTS = [
    # name,         ttf file,                           px, charset
    ('TitleXL', 'SpecialElite-Regular.ttf', 30, TITLE_XL_CHARS),
    ('Title', 'SpecialElite-Regular.ttf', 17, DEFAULT_CHARS),
    ('Body', 'IBMPlexSansCondensed-Medium.ttf', 13, DEFAULT_CHARS),
    ('BodyL', 'IBMPlexSansCondensed-Medium.ttf', 16, DEFAULT_CHARS),
    ('Ui', 'IBMPlexMono-SemiBold.ttf', 10, DEFAULT_CHARS),
    ('Label', 'IBMPlexSansCondensed-SemiBold.ttf', 11, DEFAULT_CHARS),
]


def c_array(name, data, per_line=24):
    out = ['alignas(4) static const uint8_t %s[%d] = {' % (name, len(data))]
    for i in range(0, len(data), per_line):
        out.append('  ' + ','.join('0x%02X' % b for b in data[i:i + per_line]) + ',')
    out.append('};')
    return '\n'.join(out)


def gen_fonts():
    parts = ['// AUTO-GENERATED by tools/gen_assets.py - do not edit by hand.',
             '// Fonts: Special Elite (Apache 2.0), IBM Plex (SIL OFL 1.1). See assets/fonts/.',
             '#pragma once', '#include <stdint.h>', '']
    total = 0
    tmp = os.path.join(ROOT, 'tools', '_tmp.vlw')
    for name, ttf, px, chars in FONTS:
        size, count, missing = make_vlw(os.path.join(FONT_DIR, ttf), px, tmp, chars=chars)
        req_missing = [c for c in REQUIRED if (ord(c) in chars) and hex(ord(c)) in missing]
        if req_missing:
            raise SystemExit('font %s misses required glyphs %s' % (name, req_missing))
        data = open(tmp, 'rb').read()
        total += len(data)
        parts.append('// %s: %s @ %dpx, %d glyphs, %d bytes%s' % (
            name, ttf, px, count, len(data), (' (missing: %s)' % ' '.join(missing)) if missing else ''))
        parts.append(c_array('FONT_%s' % name.upper(), data))
        parts.append('')
    os.remove(tmp)
    with open(os.path.join(SRC, 'AssetFonts.h'), 'w') as f:
        f.write('\n'.join(parts))
    print('fonts: %d bytes total' % total)


def supersample(w, h, draw_fn, ss=4):
    from PIL import Image, ImageDraw
    img = Image.new('L', (w * ss, h * ss), 0)
    d = ImageDraw.Draw(img)
    draw_fn(img, d, ss)
    return img.resize((w, h), Image.LANCZOS)


def fingerprint(w=72, h=90, seed=7):
    """Procedural fingerprint: iso-lines of a distorted whorl field."""
    from PIL import Image
    rnd = random.Random(seed)
    ss = 4
    W, H = w * ss, h * ss
    img = Image.new('L', (W, H), 0)
    px = img.load()
    cx, cy = W * 0.5, H * 0.46
    breaks = [(rnd.uniform(0, W), rnd.uniform(0, H), rnd.uniform(1.5, 4.5) * ss) for _ in range(34)]
    for y in range(H):
        for x in range(W):
            nx = (x - cx) / (W * 0.5)
            ny = (y - cy) / (H * 0.5)
            # fingertip silhouette: ellipse, flatter at bottom
            shape = nx * nx / 0.92 + (ny * ny) / (1.0 if ny < 0 else 0.86)
            if shape > 1.0:
                continue
            ang = math.atan2(ny, nx)
            r = math.sqrt((nx * 1.15) ** 2 + (ny * 0.92) ** 2)
            # whorl: spiral twist + gentle waviness
            wob = 0.35 * math.sin(nx * 7.1 + ny * 3.3) + 0.25 * math.sin(ny * 9.7 - nx * 2.1) + 0.15 * math.sin((nx + ny) * 17.0)
            field = r * 24.0 + 1.6 * math.sin(ang * 2 + r * 4.0) * r + ang / math.pi + wob
            v = 0.5 + 0.5 * math.cos(field * 2 * math.pi / 2.0)
            ridge = min(1.0, max(0.0, (v - 0.42) / 0.4))
            # fade toward edges, ink breaks
            edge = max(0.0, min(1.0, (1.0 - shape) * 3.0)) * (0.55 + 0.45 * max(0.0, 1.0 - r))
            for bx, by, br in breaks:
                if (x - bx) ** 2 + (y - by) ** 2 < br * br:
                    ridge *= 0.1
                    break
            grain = 0.75 + 0.25 * rnd.random()
            px[x, y] = int(255 * min(1.0, ridge * edge * grain))
    return img.resize((w, h), Image.LANCZOS)


def eye(w=30, h=16):
    def draw(img, d, ss):
        W, H = w * ss, h * ss
        # almond outline from two arcs
        pts_top, pts_bot = [], []
        for i in range(41):
            t = i / 40.0
            x = 1 * ss + t * (W - 2 * ss)
            yy = math.sin(t * math.pi)
            pts_top.append((x, H / 2 - yy * (H / 2 - 1.5 * ss)))
            pts_bot.append((x, H / 2 + yy * (H / 2 - 2.5 * ss)))
        d.line(pts_top, fill=255, width=int(1.6 * ss))
        d.line(pts_bot, fill=200, width=int(1.2 * ss))
        r = H * 0.30
        d.ellipse([W / 2 - r, H / 2 - r, W / 2 + r, H / 2 + r], outline=255, width=int(1.3 * ss))
        r2 = H * 0.14
        d.ellipse([W / 2 - r2, H / 2 - r2, W / 2 + r2, H / 2 + r2], fill=255)
        # lashes
        for i in range(5):
            t = 0.2 + i * 0.15
            x = 1 * ss + t * (W - 2 * ss)
            y = H / 2 - math.sin(t * math.pi) * (H / 2 - 1.5 * ss)
            d.line([(x, y), (x + (t - 0.5) * 3 * ss, y - 2.2 * ss)], fill=220, width=int(1.0 * ss))
    return supersample(w, h, draw)


def gen_art():
    parts = ['// AUTO-GENERATED by tools/gen_assets.py - do not edit by hand.',
             '#pragma once', '#include <stdint.h>', '']
    for name, img in (('FINGERPRINT', fingerprint()), ('EYE', eye())):
        w, h = img.size
        data = bytes(img.getdata())
        parts.append('static const uint16_t ART_%s_W = %d, ART_%s_H = %d;' % (name, w, name, h))
        parts.append(c_array('ART_%s' % name, data))
        parts.append('')
        img.save(os.path.join(ROOT, 'tools', '_preview_%s.png' % name.lower()))
    with open(os.path.join(SRC, 'AssetArt.h'), 'w') as f:
        f.write('\n'.join(parts))
    print('art ok')


if __name__ == '__main__':
    gen_fonts()
    gen_art()
